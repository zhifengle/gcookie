use serde::Serialize;
use std::{fmt, ops, str::FromStr};

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct Cookie {
    pub domain: String,
    pub path: String,
    pub name: String,
    pub value: String,
    pub secure: bool,
    pub http_only: bool,
    pub expires: Option<u64>,
    pub same_site: Option<i64>,
    #[serde(skip)]
    pub encrypted_value: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SiteCookie(Vec<Cookie>);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OutputFormat {
    String,
    Json,
    Netscape,
}

impl FromStr for OutputFormat {
    type Err = String;

    fn from_str(format: &str) -> Result<Self, Self::Err> {
        match format {
            "string" => Ok(Self::String),
            "json" => Ok(Self::Json),
            "netscape" => Ok(Self::Netscape),
            _ => Err(format!("Unsupported output format: {format}")),
        }
    }
}

impl SiteCookie {
    pub fn new() -> Self {
        Self(vec![])
    }

    pub fn to_json_string(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string_pretty(&self.0)
    }

    pub fn to_netscape_string(&self) -> String {
        let mut lines = vec![
            "# Netscape HTTP Cookie File".to_string(),
            "# This file was generated by gcookie.".to_string(),
        ];

        lines.extend(self.iter().map(|cookie| cookie.to_netscape_line()));
        lines.join("\n")
    }

    pub fn format(&self, format: OutputFormat) -> Result<String, serde_json::Error> {
        match format {
            OutputFormat::String => Ok(self.to_string()),
            OutputFormat::Json => self.to_json_string(),
            OutputFormat::Netscape => Ok(self.to_netscape_string()),
        }
    }
}

impl Cookie {
    fn to_netscape_line(&self) -> String {
        let include_subdomains = if self.domain.starts_with('.') {
            "TRUE"
        } else {
            "FALSE"
        };
        let secure = if self.secure { "TRUE" } else { "FALSE" };
        let expires = self.expires.unwrap_or(0);
        let domain = if self.http_only {
            format!("#HttpOnly_{}", self.domain)
        } else {
            self.domain.clone()
        };

        [
            sanitize_netscape_field(&domain),
            include_subdomains.to_string(),
            sanitize_netscape_field(&self.path),
            secure.to_string(),
            expires.to_string(),
            sanitize_netscape_field(&self.name),
            sanitize_netscape_field(&self.value),
        ]
        .join("\t")
    }
}

impl From<Vec<Cookie>> for SiteCookie {
    fn from(cookies: Vec<Cookie>) -> Self {
        Self(cookies)
    }
}

fn sanitize_netscape_field(value: &str) -> String {
    value.replace(['\t', '\r', '\n'], " ")
}

impl ops::Deref for SiteCookie {
    type Target = Vec<Cookie>;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl ops::DerefMut for SiteCookie {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}

impl fmt::Display for SiteCookie {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let cookie = self
            .iter()
            .map(|cookie| format!("{}={}", cookie.name, cookie.value))
            .collect::<Vec<_>>()
            .join("; ");
        write!(f, "{}", cookie)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cookie() -> Cookie {
        Cookie {
            domain: ".example.com".to_string(),
            path: "/".to_string(),
            name: "sid".to_string(),
            value: "abc".to_string(),
            secure: true,
            http_only: true,
            expires: Some(1_700_000_000),
            same_site: Some(1),
            encrypted_value: vec![],
        }
    }

    #[test]
    fn formats_cookie_header_string() {
        let site_cookie = SiteCookie::from(vec![cookie()]);

        assert_eq!(site_cookie.to_string(), "sid=abc");
    }

    #[test]
    fn formats_netscape_cookie_file() {
        let site_cookie = SiteCookie::from(vec![cookie()]);

        assert!(site_cookie
            .to_netscape_string()
            .contains("#HttpOnly_.example.com\tTRUE\t/\tTRUE\t1700000000\tsid\tabc"));
    }
}
